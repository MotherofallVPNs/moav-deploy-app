import 'install_script.dart';

/// Builds the detached MoaV self-update job that runs on the server.
///
/// Mirrors [InstallScript]: a bash script in `~/.moav-deploy/` launched with
/// `setsid nohup` so it survives the SSH session, with the same
/// `[moav-deploy] step N/3` and `[moav-deploy] exit=<code>` markers so
/// `SshMoavController.parseInstallStatus` reads its log unchanged.
class UpdateScript {
  UpdateScript._();

  static const scriptPath = '${InstallScript.dir}/update.sh';
  static const logPath = '${InstallScript.dir}/update.log';
  static const pidPath = '${InstallScript.dir}/update.pid';

  static const totalSteps = 3;

  /// The exact self-update invocation, verified against MoaV 2.3.0:
  /// `moav update` does `git fetch` + `git pull` on the current branch, then
  /// re-execs for the post-update checks. With stdin on `/dev/null` every
  /// prompt takes its default: local changes are **stashed** (never
  /// discarded), new `.env` defaults are appended, pinned component versions
  /// are bumped in `.env`. It does **not** rebuild or restart services; the
  /// log lists those apply steps for the operator.
  // TODO: switch to a `--yes`/non-interactive flag once upstream ships one.
  static const updateCommand = 'update';

  /// The bash job. Contains no secrets.
  static const script = r'''#!/bin/bash
# Generated by MoaV Deploy. Runs the MoaV self-update without a TTY. It never
# discards local changes (they are stashed) and never restarts services.
set -uo pipefail
export DEBIAN_FRONTEND=noninteractive
export MOAV_NONINTERACTIVE=1
INSTALL_DIR="${MOAV_INSTALL_DIR:-/opt/moav}"

step()   { echo; echo "[moav-deploy] step $1/3: $2"; }
finish() { echo; echo "[moav-deploy] exit=$1"; exit "$1"; }
moav_cmd() { if [ -x "$INSTALL_DIR/moav.sh" ]; then "$INSTALL_DIR/moav.sh" "$@"; else moav "$@"; fi; }

step 1 "Preflight"
echo "Host: $(hostname)  User: $(id -un)  Date: $(date -u +%FT%TZ)"
if [ ! -d "$INSTALL_DIR/.git" ]; then
  echo "No git checkout at $INSTALL_DIR - moav update needs one."; finish 1
fi
echo "Before: $(git -C "$INSTALL_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null) @ $(git -C "$INSTALL_DIR" rev-parse --short HEAD 2>/dev/null)"
moav_cmd --version < /dev/null 2>&1 | head -3

step 2 "Run moav update"
cd "$INSTALL_DIR" || finish 1
moav_cmd __UPDATE_COMMAND__ < /dev/null
rc=$?
if [ $rc -ne 0 ]; then echo "moav update failed (exit $rc)"; finish $rc; fi

step 3 "Report"
echo "After: $(git -C "$INSTALL_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null) @ $(git -C "$INSTALL_DIR" rev-parse --short HEAD 2>/dev/null)"
moav_cmd --version < /dev/null 2>&1 | head -3
echo "Services were not restarted. Apply any rebuild/restart steps listed above when convenient."
finish 0
''';

  /// [script] with the update invocation filled in.
  static String get body =>
      script.replaceFirst('__UPDATE_COMMAND__', updateCommand);

  /// Launches the job detached and prints `STARTED <pid>`, or `RUNNING <pid>`
  /// when one is already in flight.
  static const launch = '''
umask 077
cd "${InstallScript.dir}" || exit 1
if [ -f update.pid ] && kill -0 "\$(cat update.pid)" 2>/dev/null; then
  echo "RUNNING \$(cat update.pid)"; exit 0
fi
: > update.log
setsid nohup bash update.sh > update.log 2>&1 < /dev/null &
echo "\$!" > update.pid
echo "STARTED \$!"
''';

  /// Reports liveness (from the pid file) plus the log tail. Prints
  /// `NOJOB` when no update was ever launched.
  static String status({int tailLines = 400}) => '''
if [ ! -f "$pidPath" ]; then echo NOJOB; exit 0; fi
if kill -0 "\$(cat "$pidPath")" 2>/dev/null; then echo ALIVE; else echo DEAD; fi
echo __LOG__
tail -n $tailLines "$logPath" 2>/dev/null
''';
}
