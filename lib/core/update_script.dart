import 'apply_script.dart';
import 'install_script.dart';
import 'moav_controller.dart';

/// Builds the detached MoaV self-update job that runs on the server.
///
/// Mirrors [InstallScript]: a bash script in `~/.moav-deploy/` launched with
/// `setsid nohup` so it survives the SSH session, with the same
/// `[moav-deploy] step N/3` and `[moav-deploy] exit=<code>` markers so
/// `SshMoavController.parseInstallStatus` reads its log unchanged.
///
/// The update has to work on any installed `moav`, so the job tries the
/// non-interactive invocation first and falls back to the legacy one:
///
/// * **MoaV with PR #345** (`moav update --yes`): [updateCommand]. With
///   `MOAV_NONINTERACTIVE=1` exported the stash prompt picks option 1 and
///   every `confirm` takes its default (accept component pins and new
///   `.env` variables). Nothing reads stdin. Services are not restarted.
/// * **Older MoaV** (v2.3.1 and before): `cmd_update` rejects any unknown
///   argument with `Unknown option: --yes` and returns 1 before touching
///   git, so the first attempt is a harmless no-op there. The job detects
///   that exact line ([legacyRejectionMarker]) and re-runs plain
///   `moav update` with [legacyAnswers] on stdin: `1` answers the stash
///   prompt, `Y` the `Update component versions in .env?` prompt, and the
///   `.env` additions prompt reads EOF, which its `[Y/n]` default accepts.
///   The old `confirm` already honours `MOAV_NONINTERACTIVE=1` for the rest.
///
/// `moav update` never rebuilds or restarts anything. When launched with
/// `applyAfter` the job therefore starts [ApplyScript] itself once a new
/// revision was pulled, on the server, so the hand-over does not need the
/// app; otherwise it leaves `apply.pending` for the app to offer.
class UpdateScript {
  UpdateScript._();

  static const scriptPath = '${InstallScript.dir}/update.sh';
  static const logPath = '${InstallScript.dir}/update.log';
  static const pidPath = '${InstallScript.dir}/update.pid';

  static const totalSteps = 3;

  /// First attempt: the deterministic path on a `moav` with PR #345.
  static const updateCommand = 'update --yes';

  /// Second attempt, only when the first is rejected as an unknown option.
  static const legacyUpdateCommand = 'update';

  /// The line an older `cmd_update` prints (via `error`) for the flag it
  /// does not know. Matched as a substring so ANSI colour codes around it
  /// do not matter.
  static const legacyRejectionMarker = 'Unknown option: --yes';

  /// stdin for [legacyUpdateCommand]: stash local changes, accept pins.
  static const legacyAnswers = '1\nY\n';

  /// The bash job. Contains no secrets.
  static const script = r'''#!/bin/bash
# Generated by MoaV Deploy. Runs the MoaV self-update without a TTY. It never
# discards local changes (they are stashed). Services are rebuilt and
# restarted by the apply job, which this job starts itself when asked to.
set -uo pipefail
# World-readable like the installer: unprivileged containers read /opt/moav.
umask 022
export DEBIAN_FRONTEND=noninteractive
export MOAV_NONINTERACTIVE=1
INSTALL_DIR="${MOAV_INSTALL_DIR:-/opt/moav}"
STATE_DIR="${MOAV_DEPLOY_DIR:-$HOME/.moav-deploy}"

step()   { echo; echo "[moav-deploy] step $1/3: $2"; }
finish() { echo; echo "[moav-deploy] exit=$1"; exit "$1"; }
moav_cmd() { if [ -x "$INSTALL_DIR/moav.sh" ]; then "$INSTALL_DIR/moav.sh" "$@"; else moav "$@"; fi; }

step 1 "Preflight"
echo "Host: $(hostname)  User: $(id -un)  Date: $(date -u +%FT%TZ)"
if [ ! -d "$INSTALL_DIR/.git" ]; then
  echo "No git checkout at $INSTALL_DIR - moav update needs one."; finish 1
fi
BEFORE="$(git -C "$INSTALL_DIR" rev-parse HEAD 2>/dev/null)"
echo "Before: $(git -C "$INSTALL_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null) @ $(git -C "$INSTALL_DIR" rev-parse --short HEAD 2>/dev/null)"
moav_cmd --version < /dev/null 2>&1 | head -3

step 2 "Run moav update"
cd "$INSTALL_DIR" || finish 1
ATTEMPT="$(mktemp 2>/dev/null || echo "/tmp/moav-deploy-update.$$")"
# Attempt 1: moav with `update --yes` (PR #345). Older moav rejects the flag
# before doing anything, which attempt 2 detects below.
moav_cmd __UPDATE_COMMAND__ < /dev/null 2>&1 | tee "$ATTEMPT"
rc=${PIPESTATUS[0]}
if [ $rc -ne 0 ] && grep -q '__LEGACY_MARKER__' "$ATTEMPT"; then
  echo
  echo "[moav-deploy] This moav predates 'update --yes'; retrying the legacy way (1 = stash, Y = accept versions)."
  printf '__LEGACY_ANSWERS__' | moav_cmd __LEGACY_COMMAND__ 2>&1
  rc=$?
fi
rm -f "$ATTEMPT"
if [ $rc -ne 0 ]; then echo "moav update failed (exit $rc)"; finish $rc; fi

step 3 "Report"
echo "After: $(git -C "$INSTALL_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null) @ $(git -C "$INSTALL_DIR" rev-parse --short HEAD 2>/dev/null)"
moav_cmd --version < /dev/null 2>&1 | head -3
AFTER="$(git -C "$INSTALL_DIR" rev-parse HEAD 2>/dev/null)"
# A pulled revision stays "pending" until an apply of all services succeeds.
if [ "$BEFORE" != "$AFTER" ]; then ( umask 077; echo "$AFTER" > "$STATE_DIR/apply.pending" ); fi
if [ ! -f "$STATE_DIR/apply.pending" ]; then
  echo "Already up to date: nothing to rebuild or restart."
elif [ "${MD_APPLY_AFTER:-0}" = 1 ] && [ -f "$STATE_DIR/apply.sh" ]; then
  # Chained here, on the server, so it happens even if the phone is locked.
  if (
    cd "$STATE_DIR" || exit 1
__APPLY_SPAWN__
  ); then
    echo "[moav-deploy] apply=started (rebuild, regenerate users, start): see apply.log"
  else
    echo "[moav-deploy] apply=failed-to-start: use Apply now in the app."
  fi
else
  echo "[moav-deploy] apply=pending: services still run the previous images."
  echo "Use Apply now (rebuild + restart) in the app when convenient."
fi
finish 0
''';

  /// [script] with the update invocations filled in.
  static String get body => script
      .replaceFirst('__UPDATE_COMMAND__', updateCommand)
      .replaceFirst('__LEGACY_MARKER__', legacyRejectionMarker)
      .replaceFirst('__LEGACY_ANSWERS__', legacyAnswers.replaceAll('\n', r'\n'))
      .replaceFirst('__LEGACY_COMMAND__', legacyUpdateCommand)
      .replaceFirst(
        '__APPLY_SPAWN__',
        ApplyScript.spawn(ApplyScript.args(ApplySpec.afterUpdate)).trimRight(),
      );

  /// Launches the job detached and prints `STARTED <pid>`, `RUNNING <pid>`
  /// when one is already in flight, or `BUSY apply` while an apply job runs.
  ///
  /// With [applyAfter] the job starts the apply itself once it has pulled a
  /// new revision; the freshly uploaded apply.sh is put in place first.
  static String launch({bool applyAfter = true}) => '''
umask 077
cd "${InstallScript.dir}" || exit 1
${ApplyScript.aliveFn}
if [ -f update.pid ] && kill -0 "\$(cat update.pid)" 2>/dev/null; then
  echo "RUNNING \$(cat update.pid)"; exit 0
fi
if apply_alive; then echo "BUSY apply"; exit 0; fi
if [ -f apply.sh.new ]; then mv -f apply.sh.new apply.sh; fi
: > update.log
MD_APPLY_AFTER=${applyAfter ? 1 : 0} setsid nohup bash update.sh > update.log 2>&1 < /dev/null &
echo "\$!" > update.pid
echo "STARTED \$!"
''';

  /// Reports liveness (from the pid file) plus the log tail. Prints
  /// `NOJOB` when no update was ever launched.
  static String status({int tailLines = 400}) => '''
if [ ! -f "$pidPath" ]; then echo NOJOB; exit 0; fi
if kill -0 "\$(cat "$pidPath")" 2>/dev/null; then echo ALIVE; else echo DEAD; fi
echo __LOG__
tail -n $tailLines "$logPath" 2>/dev/null
''';
}
