import 'install_script.dart';
import 'moav_controller.dart';

/// Builds the detached "apply" job: rebuild images, optionally regenerate
/// the user bundles, then start services on the new images.
///
/// Same shape as [InstallScript] and `UpdateScript`: a bash script in
/// `~/.moav-deploy/`, launched with `setsid nohup` so it outlives the SSH
/// session, logging `[moav-deploy] step N/4` and `[moav-deploy] exit=<code>`
/// markers. On top of the pid and the log it leaves three small files so
/// the app can re-attach after any gap:
///
/// * `apply.exit`: the exit code, written on every way out (EXIT trap).
/// * `apply.job`: what was launched (`id=… no_cache=… regenerate=… services=…`).
/// * `apply.ack`: touched when the app has shown the result (Dismiss).
///
/// `apply.pending` is written by the update job when it pulled a new
/// revision and removed by a successful apply of all services.
///
/// MoaV has no one-shot for this (`moav update` only prints the steps), so
/// the job composes it; see docs/MOAV-CLI-GAPS.md.
class ApplyScript {
  ApplyScript._();

  static const dir = InstallScript.dir;
  static const scriptPath = '$dir/apply.sh';

  /// Uploads land here; [launch] moves the file over [scriptPath] only when
  /// no job is running, so a live script is never rewritten under bash.
  static const uploadPath = '$dir/apply.sh.new';
  static const logPath = '$dir/apply.log';
  static const pidPath = '$dir/apply.pid';
  static const exitPath = '$dir/apply.exit';
  static const jobPath = '$dir/apply.job';
  static const ackPath = '$dir/apply.ack';
  static const pendingPath = '$dir/apply.pending';

  static const totalSteps = 4;

  /// The bash job. Contains no secrets and takes its inputs as arguments:
  /// `apply.sh [--no-cache] [--regenerate] [service ...]`.
  static const script = r'''#!/bin/bash
# Generated by MoaV Deploy. Rebuilds images, optionally regenerates the user
# bundles, then starts services on the new images. Safe to re-run: nothing
# is deleted and a failed build leaves the running containers untouched.
set -uo pipefail
# World-readable like the installer: unprivileged containers read /opt/moav.
umask 022
export DEBIAN_FRONTEND=noninteractive
export MOAV_NONINTERACTIVE=1
INSTALL_DIR="${MOAV_INSTALL_DIR:-/opt/moav}"
STATE_DIR="${MOAV_DEPLOY_DIR:-$HOME/.moav-deploy}"

NO_CACHE=0; REGENERATE=0; SERVICES=""
for a in "$@"; do
  case "$a" in
    --no-cache) NO_CACHE=1 ;;
    --regenerate) REGENERATE=1 ;;
    -*|*[!a-zA-Z0-9_-]*) echo "Unknown argument: $a"; exit 2 ;;
    *) SERVICES="${SERVICES:+$SERVICES }$a" ;;
  esac
done

# The result is written on every way out, so a poll after any gap finds it.
on_exit() {
  rc=$?
  trap - EXIT
  if [ "$rc" -eq 0 ] && [ -z "$SERVICES" ]; then rm -f "$STATE_DIR/apply.pending"; fi
  echo; echo "[moav-deploy] exit=$rc"
  ( umask 077; echo "$rc" > "$STATE_DIR/apply.exit.tmp" && mv -f "$STATE_DIR/apply.exit.tmp" "$STATE_DIR/apply.exit" )
}
trap on_exit EXIT
trap 'echo "Interrupted (SIGTERM)"; exit 143' TERM
trap 'echo "Interrupted (SIGINT)"; exit 130' INT

step() { echo; echo "[moav-deploy] step $1/4: $2"; }
moav_cmd() { if [ -x "$INSTALL_DIR/moav.sh" ]; then "$INSTALL_DIR/moav.sh" "$@"; else moav "$@"; fi; }
env_val() {
  grep -E "^$1=" "$INSTALL_DIR/.env" 2>/dev/null | tail -n 1 | cut -d= -f2- \
    | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}
# Same RAM tiers as compose_build in MoaV lib/build.sh: a small box compiles
# one image at a time instead of running out of memory.
compose_build() {
  local mb limit
  mb="$(awk '/MemTotal/ {printf "%.0f", $2/1024}' /proc/meminfo 2>/dev/null)"
  mb="${mb:-0}"
  limit="${MOAV_BUILD_PARALLEL:-}"
  if [ -z "$limit" ]; then
    if [ "$mb" -gt 0 ] && [ "$mb" -le 3072 ]; then limit=1
    elif [ "$mb" -gt 0 ] && [ "$mb" -le 6144 ]; then limit=2
    else limit=0; fi
  fi
  if [ "$limit" -ge 1 ] 2>/dev/null; then
    echo "Build concurrency limited to $limit (RAM ${mb}MB)"
    COMPOSE_BAKE=false COMPOSE_PARALLEL_LIMIT="$limit" docker compose "$@" < /dev/null
  else
    docker compose "$@" < /dev/null
  fi
}

( umask 077; echo "id=$(date +%s)-$$ no_cache=$NO_CACHE regenerate=$REGENERATE services=$(echo "$SERVICES" | tr ' ' ',')" > "$STATE_DIR/apply.job" )

step 1 "Preflight"
echo "Host: $(hostname)  User: $(id -un)  Date: $(date -u +%FT%TZ)"
echo "Scope: ${SERVICES:-all enabled services}  no-cache: $NO_CACHE  regenerate users: $REGENERATE"
if [ ! -f "$INSTALL_DIR/.env" ]; then
  echo "No MoaV install with a .env at $INSTALL_DIR - install and bootstrap first."; exit 1
fi
cd "$INSTALL_DIR" || exit 1
if ! docker compose version > /dev/null 2>&1; then
  echo "docker compose is not available for $(id -un)."; exit 1
fi
PROFILE_ARGS=""
if [ -z "$SERVICES" ]; then
  for p in $(env_val DEFAULT_PROFILES); do
    case "$p" in *[!a-zA-Z0-9_-]*) ;; *) PROFILE_ARGS="$PROFILE_ARGS --profile $p" ;; esac
  done
  if [ -z "$PROFILE_ARGS" ]; then
    echo "DEFAULT_PROFILES is not set in $INSTALL_DIR/.env, so there is no service set to rebuild."
    echo "Run 'moav start' once on the server to choose the services, then try again."
    exit 1
  fi
  echo "Profiles:$PROFILE_ARGS"
fi

step 2 "Build images"
CACHE_FLAG=""
if [ "$NO_CACHE" = 1 ]; then CACHE_FLAG="--no-cache"; echo "Forced rebuild: the Docker layer cache is ignored."; fi
if [ -n "$SERVICES" ]; then
  # shellcheck disable=SC2086
  compose_build --profile all build $CACHE_FLAG $SERVICES
else
  # The profiles this box runs, like bootstrap; never `--profile all`.
  # shellcheck disable=SC2086
  compose_build $PROFILE_ARGS build $CACHE_FLAG
fi
rc=$?
if [ $rc -ne 0 ]; then
  echo "Build failed (exit $rc). Nothing was restarted: services keep running on the previous images."
  exit $rc
fi

step 3 "Regenerate user bundles"
REGEN_RC=0
if [ "$REGENERATE" = 1 ]; then
  moav_cmd regenerate-users < /dev/null
  REGEN_RC=$?
  if [ $REGEN_RC -ne 0 ]; then echo "moav regenerate-users failed (exit $REGEN_RC); continuing so services still move to the new images."; fi
else
  echo "Skipped (not requested)."
fi

step 4 "Start services on the new images"
# shellcheck disable=SC2086
moav_cmd start $SERVICES < /dev/null
rc=$?
if [ $rc -ne 0 ]; then echo "moav start failed (exit $rc)"; exit $rc; fi
moav_cmd status < /dev/null 2>&1 || true
if [ $REGEN_RC -ne 0 ]; then
  echo "Services are on the new images, but the user bundles were not regenerated (exit $REGEN_RC)."
  exit $REGEN_RC
fi
echo "Applied: services are running on the rebuilt images."
exit 0
''';

  /// Shell test for "the job in apply.pid is still running", run from
  /// inside [dir]. The exit file wins over the pid, and on Linux the pid
  /// must still be this script, so a pid reused after a reboot is not it.
  static const aliveFn = r'''
apply_alive() {
  [ -f apply.pid ] && [ ! -f apply.exit ] || return 1
  p="$(cat apply.pid 2>/dev/null)"
  [ -n "$p" ] && kill -0 "$p" 2>/dev/null || return 1
  [ ! -r "/proc/$p/cmdline" ] || tr '\0' ' ' < "/proc/$p/cmdline" | grep -q 'apply\.sh'
}
''';

  /// Starts apply.sh detached with [args], from inside [dir]. Shared by
  /// [launch] and the update job, which chains into the apply on its own.
  static String spawn(String args) => '''
( umask 077
  rm -f apply.exit apply.ack apply.job
  : > apply.log
  \$(command -v setsid) nohup bash apply.sh $args > apply.log 2>&1 < /dev/null &
  echo "\$!" > apply.pid )
''';

  /// A compose service name; a leading `-` would read as an option.
  static final validService = RegExp(r'^[a-zA-Z0-9][a-zA-Z0-9_-]*$');

  /// Arguments for [spec]. Service names are validated here, so they need
  /// no quoting.
  static String args(ApplySpec spec) {
    for (final s in spec.services) {
      if (!validService.hasMatch(s)) {
        throw ArgumentError.value(s, 'service', 'not a service name');
      }
    }
    return [
      if (spec.noCache) '--no-cache',
      if (spec.regenerateUsers) '--regenerate',
      ...spec.services,
    ].join(' ');
  }

  /// Launches the job detached and prints `STARTED <pid>`; `RUNNING <pid>`
  /// when one is already in flight, `BUSY update` while an update job runs.
  static String launch(ApplySpec spec) => '''
umask 077
cd "$dir" || exit 1
$aliveFn
if [ -f update.pid ] && kill -0 "\$(cat update.pid)" 2>/dev/null; then
  echo "BUSY update"; exit 0
fi
if apply_alive; then echo "RUNNING \$(cat apply.pid)"; exit 0; fi
if [ -f apply.sh.new ]; then mv -f apply.sh.new apply.sh; fi
${spawn(args(spec))}
echo "STARTED \$(cat apply.pid)"
''';

  /// Liveness, the result files and the log tail. The latest step marker is
  /// read from the whole log: a build prints far more than [tailLines].
  static String status({int tailLines = 400}) => '''
cd "$dir" 2>/dev/null || { echo NOJOB; exit 0; }
$aliveFn
if [ -f apply.pending ]; then echo PENDING; fi
if [ ! -f apply.pid ]; then echo NOJOB; exit 0; fi
if apply_alive; then echo ALIVE; else echo DEAD; fi
if [ -f apply.exit ]; then echo "EXIT=\$(head -c 16 apply.exit)"; fi
if [ -f apply.ack ]; then echo ACKED; fi
if [ -f apply.job ]; then echo "JOB=\$(head -n 1 apply.job)"; fi
echo "STEP=\$(grep -a '^\\[moav-deploy\\] step ' apply.log 2>/dev/null | tail -n 1)"
echo __LOG__
tail -n $tailLines apply.log 2>/dev/null
''';

  /// Marks the ended job's result as seen, so it is not shown again.
  static const acknowledge = '''
cd "$dir" 2>/dev/null || exit 0
$aliveFn
if [ -f apply.pid ] && ! apply_alive; then ( umask 077; : > apply.ack ); fi
''';

  /// Parses the `JOB=` line written by the script: its id and its spec.
  static ({String id, ApplySpec spec})? parseJob(String line) {
    final fields = <String, String>{};
    for (final part in line.trim().split(RegExp(r'\s+'))) {
      final i = part.indexOf('=');
      if (i > 0) fields[part.substring(0, i)] = part.substring(i + 1);
    }
    final id = fields['id'];
    if (id == null || id.isEmpty) return null;
    final spec = ApplySpec(
      services: [
        for (final s in (fields['services'] ?? '').split(','))
          if (validService.hasMatch(s)) s,
      ],
      noCache: fields['no_cache'] == '1',
      regenerateUsers: fields['regenerate'] == '1',
    );
    return (id: id, spec: spec);
  }
}
