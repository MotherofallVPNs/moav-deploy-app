import 'moav_controller.dart';
import 'moav_services.dart';
import 'ssh_connection.dart';

/// Builds the detached, idempotent install job that runs on the server.
///
/// A bash script plus a mode-0600 `spec.env` are written to `~/.moav-deploy/`.
/// The script drives upstream `install.sh` through its own non-interactive
/// contract (`MOAV_NONINTERACTIVE=1`, `MOAV_DOMAIN` + `MOAV_EMAIL` or
/// `MOAV_DOMAINLESS=1`, `MOAV_ADMIN_PASSWORD`, `ENABLE_*`) so the installer
/// creates `.env`, disables certificate-dependent protocols itself when there
/// is no domain, and derives `DEFAULT_PROFILES`. Those inputs are confined to
/// a subshell; `moav bootstrap`/`moav start` then run in a clean environment
/// so bootstrap reads the services from `.env` instead of the exported
/// `ENABLE_*`. It never modifies an existing `/opt/moav`, only fills empty
/// `.env` values on an existing box (the installer's own rule), and bootstraps
/// only a never-bootstrapped box.
/// `[moav-deploy] step N/3` and `[moav-deploy] exit=<code>` markers make the
/// log self-describing. The three steps are documented in docs/ARCHITECTURE.md.
class InstallScript {
  InstallScript._();

  static const dir = '.moav-deploy';
  static const scriptPath = '$dir/deploy.sh';
  static const specPath = '$dir/spec.env';
  static const logPath = '$dir/deploy.log';

  static const totalSteps = 3;
  static const stepMarker = '[moav-deploy] step ';
  static const exitMarker = '[moav-deploy] exit=';

  /// Installer inputs as a sourceable env file. Values are single-quoted so
  /// any character is safe; the file is never echoed to the log.
  ///
  /// `MD_ENABLE` carries the `ENABLE_*=true|false` pairs for the selected
  /// services; the job exports them to `install.sh` only when no `.env`
  /// exists yet. `DEFAULT_PROFILES` is derived from them by the installer.
  static String spec(InstallSpec s) {
    final enable = MoavProfiles.enableFlagsFor(s.profiles)
        .entries
        .map((e) => '${e.key}=${e.value}')
        .join(' ');
    final lines = <String>[
      'MD_DOMAIN=${SshConnection.shellQuote(s.domain.trim())}',
      'MD_EMAIL=${SshConnection.shellQuote(s.email.trim())}',
      'MD_ADMIN_PASSWORD=${SshConnection.shellQuote(s.adminPassword)}',
      'MD_ENABLE=${SshConnection.shellQuote(enable)}',
    ];
    for (final e in s.extraEnv.entries) {
      final key = e.key.trim();
      if (!RegExp(r'^[A-Z_][A-Z0-9_]*$').hasMatch(key)) continue;
      lines.add('export $key=${SshConnection.shellQuote(e.value)}');
    }
    return '${lines.join('\n')}\n';
  }

  /// The bash job. Contains no secrets.
  static const script = r'''#!/bin/bash
# Generated by MoaV Deploy. Idempotent: safe to re-run on a box that already
# has MoaV. It never deletes /opt/moav, users, keys or state.
set -uo pipefail
# The launcher runs with umask 077 so its own files stay private. The clone
# must be world-readable: unprivileged containers (xray, admin) read /opt/moav.
umask 022
export DEBIAN_FRONTEND=noninteractive
INSTALL_DIR="${MOAV_INSTALL_DIR:-/opt/moav}"
SPEC="$HOME/.moav-deploy/spec.env"
if [ -f "$SPEC" ]; then . "$SPEC"; fi
MD_DOMAIN="${MD_DOMAIN:-}"; MD_EMAIL="${MD_EMAIL:-}"; MD_ADMIN_PASSWORD="${MD_ADMIN_PASSWORD:-}"
MD_ENABLE="${MD_ENABLE:-}"

step()   { echo; echo "[moav-deploy] step $1/3: $2"; }
finish() { rm -f "$SPEC"; echo; echo "[moav-deploy] exit=$1"; exit "$1"; }
moav_cmd() { if [ -x "$INSTALL_DIR/moav.sh" ]; then "$INSTALL_DIR/moav.sh" "$@"; else moav "$@"; fi; }

step 1 "Preflight"
echo "Host: $(hostname)  User: $(id -un)  Date: $(date -u +%FT%TZ)"
BOOTSTRAP=1
if [ -d "$INSTALL_DIR" ]; then
  echo "Existing MoaV install found at $INSTALL_DIR - it will be kept as-is (no git changes, no data removed)."
  if [ -d "$INSTALL_DIR/outputs/bundles" ] && [ -n "$(ls -A "$INSTALL_DIR/outputs/bundles" 2>/dev/null)" ]; then
    BOOTSTRAP=0
    echo "Already bootstrapped - bootstrap and start will be skipped. Existing users, keys and configs untouched."
    echo "(Re-run later on purpose with: moav bootstrap --yes)"
  fi
else
  echo "No MoaV install at $INSTALL_DIR - performing a fresh install."
fi

step 2 "Run MoaV installer (non-interactive .env setup)"
# install.sh's own automation contract: it creates .env (0600) or fills only
# empty values in an existing one, never updates an existing checkout,
# disables the certificate-dependent protocols itself when there is no domain,
# and derives DEFAULT_PROFILES from the ENABLE_* flags. The MOAV_*/ENABLE_*
# inputs live only inside this subshell: exported in the parent they would
# leak into 'moav bootstrap', which reads ENABLE_* from the environment ahead
# of .env and would re-enable the cert protocols domainless mode just disabled.
# Bootstrap and start run in step 3 with a clean environment reading only .env.
(
  export MOAV_NONINTERACTIVE=1 MOAV_BRANCH="${MOAV_BRANCH:-main}" MOAV_INSTALL_DIR="$INSTALL_DIR"
  export MOAV_ADMIN_PASSWORD="$MD_ADMIN_PASSWORD"
  if [ -n "$MD_DOMAIN" ]; then
    export MOAV_DOMAIN="$MD_DOMAIN" MOAV_EMAIL="$MD_EMAIL"
    echo "Domain: $MD_DOMAIN (Let's Encrypt email set)"
  else
    export MOAV_DOMAINLESS=1
    echo "No domain: domainless mode (the installer disables certificate-dependent protocols itself)"
  fi
  # The selected services only shape a .env this run creates; an existing .env
  # keeps its ENABLE_* flags (change them later from the Services tab).
  if [ ! -f "$INSTALL_DIR/.env" ]; then
    for kv in $MD_ENABLE; do
      case "$kv" in ENABLE_*=true|ENABLE_*=false) export "$kv" ;; esac
    done
    [ -n "$MD_ENABLE" ] && echo "ENABLE_* flags passed from the selected services"
  else
    echo "Existing .env: ENABLE_* flags kept as configured"
  fi
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL https://moav.sh/install.sh | bash
  else
    wget -qO- https://moav.sh/install.sh | bash
  fi
)
rc=$?
unset MD_ADMIN_PASSWORD
if [ $rc -ne 0 ]; then echo "Installer failed (exit $rc)"; finish $rc; fi

step 3 "Bootstrap and start"
cd "$INSTALL_DIR" || finish 1
if [ "$BOOTSTRAP" = 1 ]; then
  # Clean environment: no ENABLE_*/MOAV_* exports, so bootstrap reads .env only
  # (install.sh already set DOMAIN, services and the domainless disables there).
  echo "Bootstrapping (keys, certs, first user) and starting services..."
  moav_cmd bootstrap --yes < /dev/null
  rc=$?
  if [ $rc -ne 0 ]; then echo "Bootstrap failed (exit $rc)"; finish $rc; fi
  moav_cmd start < /dev/null
  rc=$?
  if [ $rc -ne 0 ]; then echo "Start failed (exit $rc)"; finish $rc; fi
  echo "Bootstrapped and started. Current status:"
else
  echo "Services left untouched (existing install). Current status:"
fi
moav_cmd status < /dev/null 2>&1 || true
finish 0
''';

  /// Shell that launches the job detached from the SSH session and prints
  /// the PID. If a job is already running it prints that PID instead.
  /// `umask 077` keeps deploy.log and deploy.pid private; deploy.sh itself
  /// resets to 022 before the installer clones `/opt/moav`.
  static const launch = '''
umask 077
cd "$dir" || exit 1
if [ -f deploy.pid ] && kill -0 "\$(cat deploy.pid)" 2>/dev/null; then
  echo "RUNNING \$(cat deploy.pid)"; exit 0
fi
: > deploy.log
setsid nohup bash deploy.sh > deploy.log 2>&1 < /dev/null &
echo "\$!" > deploy.pid
echo "STARTED \$!"
''';

  /// Shell that reports liveness plus the log tail.
  static String status(String pid, {int tailLines = 400}) => '''
if kill -0 ${SshConnection.shellQuote(pid)} 2>/dev/null; then echo ALIVE; else echo DEAD; fi
echo __LOG__
tail -n $tailLines "$logPath" 2>/dev/null
''';
}
