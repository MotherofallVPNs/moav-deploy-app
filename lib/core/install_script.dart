import 'moav_controller.dart';
import 'ssh_connection.dart';

/// Builds the detached, idempotent install job that runs on the server.
///
/// A bash script plus a mode-0600 `spec.env` are written to `~/.moav-deploy/`.
/// The script never modifies an existing `/opt/moav`, runs the upstream
/// installer without a TTY, fills only empty `.env` values, bootstraps only a
/// never-bootstrapped box, and starts services only after its own bootstrap.
/// `[moav-deploy] step N/5` and `[moav-deploy] exit=<code>` markers make the
/// log self-describing. The five steps are documented in docs/ARCHITECTURE.md.
class InstallScript {
  InstallScript._();

  static const dir = '.moav-deploy';
  static const scriptPath = '$dir/deploy.sh';
  static const specPath = '$dir/spec.env';
  static const logPath = '$dir/deploy.log';

  static const totalSteps = 5;
  static const stepMarker = '[moav-deploy] step ';
  static const exitMarker = '[moav-deploy] exit=';

  /// Installer inputs as a sourceable env file. Values are single-quoted so
  /// any character is safe; the file is never echoed to the log.
  static String spec(InstallSpec s) {
    final lines = <String>[
      'MD_DOMAIN=${SshConnection.shellQuote(s.domain.trim())}',
      'MD_EMAIL=${SshConnection.shellQuote(s.email.trim())}',
      'MD_ADMIN_PASSWORD=${SshConnection.shellQuote(s.adminPassword)}',
    ];
    for (final e in s.extraEnv.entries) {
      final key = e.key.trim();
      if (!RegExp(r'^[A-Z_][A-Z0-9_]*$').hasMatch(key)) continue;
      lines.add('export $key=${SshConnection.shellQuote(e.value)}');
    }
    return '${lines.join('\n')}\n';
  }

  /// The bash job. Contains no secrets.
  static const script = r'''#!/bin/bash
# Generated by MoaV Deploy. Idempotent: safe to re-run on a box that already
# has MoaV. It never deletes /opt/moav, users, keys or state.
set -uo pipefail
export DEBIAN_FRONTEND=noninteractive
INSTALL_DIR="${MOAV_INSTALL_DIR:-/opt/moav}"
SPEC="$HOME/.moav-deploy/spec.env"
if [ -f "$SPEC" ]; then . "$SPEC"; fi
MD_DOMAIN="${MD_DOMAIN:-}"; MD_EMAIL="${MD_EMAIL:-}"; MD_ADMIN_PASSWORD="${MD_ADMIN_PASSWORD:-}"

step()   { echo; echo "[moav-deploy] step $1/5: $2"; }
finish() { rm -f "$SPEC"; echo; echo "[moav-deploy] exit=$1"; exit "$1"; }
moav_cmd() { if [ -x "$INSTALL_DIR/moav.sh" ]; then "$INSTALL_DIR/moav.sh" "$@"; else moav "$@"; fi; }

step 1 "Preflight"
echo "Host: $(hostname)  User: $(id -un)  Date: $(date -u +%FT%TZ)"
if [ -d "$INSTALL_DIR" ]; then
  echo "Existing MoaV install found at $INSTALL_DIR - it will be kept as-is (no git changes, no data removed)."
else
  echo "No MoaV install at $INSTALL_DIR - performing a fresh install."
fi

step 2 "Run MoaV installer (non-interactive)"
# Without a TTY the installer keeps an existing checkout untouched, installs
# missing packages and installs the global 'moav' command.
if command -v curl >/dev/null 2>&1; then
  curl -fsSL https://moav.sh/install.sh | MOAV_BRANCH="${MOAV_BRANCH:-main}" MOAV_INSTALL_DIR="$INSTALL_DIR" bash
else
  wget -qO- https://moav.sh/install.sh | MOAV_BRANCH="${MOAV_BRANCH:-main}" MOAV_INSTALL_DIR="$INSTALL_DIR" bash
fi
rc=$?
if [ $rc -ne 0 ]; then echo "Installer failed (exit $rc)"; finish $rc; fi

step 3 "Configure .env"
cd "$INSTALL_DIR" || finish 1
if [ ! -f .env ]; then
  cp .env.example .env && chmod 600 .env && echo "Created .env from .env.example"
fi
# set_if_empty KEY VALUE: only fills empty or placeholder values.
set_if_empty() {
  local key="$1" val="$2" cur tmp
  [ -n "$val" ] || return 0
  cur=$(sed -n "s/^${key}=//p" .env | head -1); cur=${cur%\"}; cur=${cur#\"}
  if [ -n "$cur" ] && [ "$cur" != "change_me_to_something_secure" ]; then
    echo "  $key already configured - kept existing value"; return 0
  fi
  tmp=$(mktemp)
  MD_VAL="$val" awk -v k="$key" 'BEGIN{v=ENVIRON["MD_VAL"]; done=0}
    index($0, k"=")==1 && !done {print k"=\"" v "\""; done=1; next}
    {print}
    END{if(!done) print k"=\"" v "\""}' .env > "$tmp" && cat "$tmp" > .env
  rm -f "$tmp"
  echo "  $key set"
}
set_if_empty DOMAIN "$MD_DOMAIN"
set_if_empty ACME_EMAIL "$MD_EMAIL"
set_if_empty ADMIN_PASSWORD "$MD_ADMIN_PASSWORD"
unset MD_ADMIN_PASSWORD

step 4 "Bootstrap (keys, certificates, configs)"
BOOTSTRAPPED_NOW=0
if [ -d outputs/bundles ] && [ -n "$(ls -A outputs/bundles 2>/dev/null)" ]; then
  echo "Already bootstrapped - skipping. Existing users, keys and configs untouched."
  echo "(Re-run later on purpose with: moav bootstrap --yes)"
else
  moav_cmd bootstrap --yes < /dev/null
  rc=$?
  if [ $rc -ne 0 ]; then echo "Bootstrap failed (exit $rc)"; finish $rc; fi
  BOOTSTRAPPED_NOW=1
fi

step 5 "Start services"
if [ "$BOOTSTRAPPED_NOW" = 1 ]; then
  moav_cmd start < /dev/null
  rc=$?
  if [ $rc -ne 0 ]; then echo "Start failed (exit $rc)"; finish $rc; fi
else
  echo "Services left untouched (existing install). Current status:"
  moav_cmd status < /dev/null 2>&1 || true
fi
finish 0
''';

  /// Shell that launches the job detached from the SSH session and prints
  /// the PID. If a job is already running it prints that PID instead.
  static const launch = '''
umask 077
cd "$dir" || exit 1
if [ -f deploy.pid ] && kill -0 "\$(cat deploy.pid)" 2>/dev/null; then
  echo "RUNNING \$(cat deploy.pid)"; exit 0
fi
: > deploy.log
setsid nohup bash deploy.sh > deploy.log 2>&1 < /dev/null &
echo "\$!" > deploy.pid
echo "STARTED \$!"
''';

  /// Shell that reports liveness plus the log tail.
  static String status(String pid, {int tailLines = 400}) => '''
if kill -0 ${SshConnection.shellQuote(pid)} 2>/dev/null; then echo ALIVE; else echo DEAD; fi
echo __LOG__
tail -n $tailLines "$logPath" 2>/dev/null
''';
}
